"""Measure source canvases without modifying images. Composite references are art-directed.
Run after replacing illustrations: python tools/measure-actors.py (requires Pillow).
"""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
metrics={}
# (standing body reference, visible floor). Keep registered compositions on one scale.
composites={
 'story-v72':(1080,1324), 'purple-v73':(1140,1324),
 'red/v68':(1315,1462), 'red/v70':(1315,1462),
}
for folder in ['yellow','red','motion-v79','story-v72','purple-v73','coherent-v80','aqua','finale-v78']:
 for p in sorted((root/'assets/optimized'/folder).rglob('*.webp')):
  im=Image.open(p).convert('RGBA');w,h=im.size
  bbox=im.getchannel('A').point(lambda a:255 if a>32 else 0).getbbox()
  if not bbox:continue
  l,t,r,b=bbox;name=p.relative_to(root/'assets/optimized').with_suffix('').as_posix()
  body=b-t;floor=b;kind='portrait'
  if name.startswith('yellow/') and 32<=int(p.stem)<=40:
   body=1000 if int(p.stem)<38 else 960;floor=1014;kind='composition'
  elif name=='yellow/41':body=1160;floor=1171;kind='composition'
  else:
   for prefix,(reference,baseline) in composites.items():
    if name.startswith(prefix+'/') and w==h or name.startswith(prefix+'/') and prefix.startswith('red/'):
     body=reference;floor=baseline;kind='composition';break
  if name.startswith('coherent-v80/'):
   kind='group' if p.stem in ['team-a','team-b','gather','embrace','hug'] else 'composition'
   if p.stem.startswith('team-'):body=690;floor=739
   elif p.stem in ['gather','embrace','hug']:body=1070;floor=1134
   else:body=1140;floor=1324
  if name=='aqua/catch':body=710;floor=905;kind='composition'
  if name=='story-v72/tired-transparent':body=1080*w/1400;floor=b;kind='composition'
  # Upright characters inside a doorway must match their separate walking poses.
  body_refs={'story-v72/farewell':962,'story-v72/closed':1116,'story-v72/closing':1112,
   'purple-v73/wave':1163,'purple-v73/greeting':1058,'purple-v73/farewell':1065,'purple-v73/closing':1132}
  if name in body_refs:body=body_refs[name]
  # A crouch or tucked jump changes silhouette height, not the anatomical scale.
  posture={'yellow/4':.72,'yellow/5':.88,'yellow/6':.78,'yellow/17':.72,'aqua/red-flight':.8,'story-v72/landing':.8}.get(name,1)
  if kind=='portrait':body=body/posture
  metrics[name]={'w':w,'h':h,'center':(l+r)/2,'floor':floor,'body':round(body,3),'bounds':[l,t,r,b],'kind':kind}
(root/'actor-metrics.js').write_text('/* Measured alpha bounds and reviewed standing-height references. Generated by tools/measure-actors.py. */\nwindow.ColorClikActorMetrics='+json.dumps(metrics,separators=(',',':'))+';\n')
print(f'{len(metrics)} actor references measured; original images unchanged')
